#!/usr/bin/env python3
"""Generate acs/FAA-S-ACS-1.md, the whole mechanic ACS as one Markdown file.

Usage:
    python3 scripts/build_acs.py            # write acs/FAA-S-ACS-1.md
    python3 scripts/build_acs.py --check    # print counts, write nothing

The ACS data lives in the vendor/faa-acs-data git submodule
(https://github.com/campeterson/faa-acs-data). The submodule commit is written
into the generated file so it's clear which ACS data it was built from.

Layout: one `##` per Area (General / Airframe / Powerplant), one `###` per
Subject with its code, then the objective and the Knowledge, Risk Management
and Skill elements, each with its code and verbatim text. Archived elements
are excluded.

This is the only place ACS data enters the repo. When a separate system starts
providing ACS data, replace this script.
"""
import argparse
import json
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENDOR = ROOT / "vendor" / "faa-acs-data"
DATA_DIR = VENDOR / "FAA-S-ACS-1" / "data"
ELEMENTS = DATA_DIR / "elements.json"
SOURCE_NOTE = VENDOR / "FAA-S-ACS-1" / "source" / "SOURCE.txt"
REGISTRY = VENDOR / "acs_registry.json"
OUT = ROOT / "acs" / "FAA-S-ACS-1.md"
DATA_URL = "https://github.com/campeterson/faa-acs-data"

SECTIONS = [
    ("K", "Knowledge", "The applicant demonstrates understanding of:"),
    ("R", "Risk Management", "The applicant demonstrates the ability to identify, assess, "
          "and mitigate risks associated with:"),
    ("S", "Skills", "The applicant demonstrates the ability to:"),
]

# Sanity checks: subject code -> expected (K, R, S). Add one per subject as it's built.
EXPECTED = {
    "AM.II.E": (13, 6, 29),
}


def data_commit() -> str:
    try:
        return subprocess.check_output(
            ["git", "-C", str(VENDOR), "rev-parse", "HEAD"], text=True).strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        sys.exit("vendor/faa-acs-data is missing. Run: git submodule update --init")


def registry_entry() -> dict:
    reg = json.loads(REGISTRY.read_text(encoding="utf-8"))
    entries = reg if isinstance(reg, list) else reg.get("documents", [])
    for entry in entries:
        if isinstance(entry, dict) and entry.get("code") == "FAA-S-ACS-1":
            return entry
    return {}


def subject_code(e) -> str:
    return f"AM.{e['area_roman']}.{e['task_letter']}"


def build(elements, commit: str) -> tuple[str, dict]:
    reg = registry_entry()
    title = reg.get("title", "Aviation Mechanic General, Airframe, and Powerplant "
                             "Airman Certification Standards")
    dated = reg.get("revision_date", "")

    lines = [
        f"# FAA-S-ACS-1 {title}",
        "",
        f"ACS dated {dated}." if dated else "ACS date not recorded in the data.",
        "",
        "Generated by `scripts/build_acs.py`. Do not edit by hand.",
        f"ACS data: {DATA_URL} at commit `{commit}`.",
        "Element text is verbatim from the ACS. Archived elements are excluded.",
        "",
        "Element codes: `AM.<Area>.<Subject>.<K|R|S><number>`. "
        "K = Knowledge, R = Risk Management, S = Skill.",
        "",
    ]

    counts = {}
    area = None
    subject = None
    rows = [e for e in elements if not e["archived"]]
    for e in rows:
        if e["area_roman"] != area:
            area = e["area_roman"]
            lines += [f"## {area}. {e['area_title']}", ""]
        code = subject_code(e)
        if code != subject:
            subject = code
            lines += [f"### {code} {e['task_title']}", "", "**Objective:** " + e["objective"], ""]
            if e.get("notes"):
                lines += ["**Note:** " + e["notes"], ""]
            subj_rows = [x for x in rows if subject_code(x) == code]
            counts[code] = Counter(x["element_type"] for x in subj_rows)
            for etype, heading, lead in SECTIONS:
                section = [x for x in subj_rows if x["element_type"] == etype]
                lines += [f"#### {code} {heading}", "", lead, ""]
                if not section:
                    lines += ["(None listed.)", ""]
                    continue
                for x in section:
                    indent = "  " if x["parent_code"] else ""
                    lines.append(f"{indent}- **{x['code']}** {x['text']}")
                lines.append("")
    return "\n".join(lines), counts


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="print counts, write nothing")
    args = ap.parse_args()

    elements = json.loads(ELEMENTS.read_text(encoding="utf-8"))
    text, counts = build(elements, data_commit())

    # Every element code must be unique and every non-archived element written.
    codes = [e["code"] for e in elements if not e["archived"]]
    dupes = [c for c, n in Counter(codes).items() if n > 1]
    missing = [c for c in codes if f"**{c}**" not in text]
    ok = not dupes and not missing
    for code, (k, r, s) in EXPECTED.items():
        got = (counts[code]["K"], counts[code]["R"], counts[code]["S"])
        status = "ok" if got == (k, r, s) else "MISMATCH"
        ok &= got == (k, r, s)
        print(f"{code}: K={got[0]} R={got[1]} S={got[2]} (expected {k}/{r}/{s}) {status}")
    print(f"{len(counts)} subjects, {len(codes)} elements"
          + (f", DUPLICATE codes: {dupes}" if dupes else "")
          + (f", MISSING from output: {missing[:5]}" if missing else ""))
    if not ok:
        sys.exit(1)

    if not args.check:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)} ({len(text.encode()):,} bytes)")


if __name__ == "__main__":
    main()
