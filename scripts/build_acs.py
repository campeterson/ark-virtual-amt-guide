#!/usr/bin/env python3
"""Generate a subject's acs.md from Cam's FAA ACS data (FAA-S-ACS-1).

Usage:
    python3 scripts/build_acs.py AM.II.E
    python3 scripts/build_acs.py --all-built   # regenerate every subject that already has an acs.md

The ACS data lives in the vendor/faa-acs-data git submodule
(https://github.com/campeterson/faa-acs-data). The submodule commit is written
into each generated file so it's clear which ACS data a subject was built from.

This is the only place ACS data enters the repo. When a separate system starts
providing ACS data, replace this script.
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENDOR = ROOT / "vendor" / "faa-acs-data"
ELEMENTS = VENDOR / "FAA-S-ACS-1" / "data" / "elements.json"
DATA_URL = "https://github.com/campeterson/faa-acs-data"

CATEGORY_BY_AREA = {"I": "general", "II": "airframe", "III": "powerplant"}
SECTIONS = [
    ("K", "Knowledge", "The applicant demonstrates understanding of:"),
    ("R", "Risk Management", "The applicant demonstrates the ability to identify, assess, "
          "and mitigate risks associated with:"),
    ("S", "Skills", "The applicant demonstrates the ability to:"),
]


def slugify(title: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")


def data_commit() -> str:
    try:
        return subprocess.check_output(
            ["git", "-C", str(VENDOR), "rev-parse", "HEAD"], text=True).strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        sys.exit("vendor/faa-acs-data is missing. Run: git submodule update --init")


def load_elements():
    return json.loads(ELEMENTS.read_text(encoding="utf-8"))


def subject_path(subject_code: str, title: str, area: str) -> Path:
    return ROOT / "subjects" / CATEGORY_BY_AREA[area] / slugify(title) / "acs.md"


def build(subject_code: str, elements, commit: str) -> Path:
    prefix = subject_code + "."
    rows = [e for e in elements
            if e["code"].startswith(prefix) and not e["archived"]]
    if not rows:
        sys.exit(f"No elements found for {subject_code}")
    first = rows[0]
    area, letter, title = first["area_roman"], first["task_letter"], first["task_title"]

    lines = [
        f"# {subject_code} {title}",
        "",
        f"FAA-S-ACS-1, Aviation Mechanic General, Airframe, and Powerplant Airman "
        f"Certification Standards. Area {area}. {first['area_title']}, "
        f"Subject {letter}. {title}.",
        "",
        "Generated by `scripts/build_acs.py`. Do not edit by hand.",
        f"ACS data: {DATA_URL} at commit `{commit}`.",
        "Element text is verbatim from the ACS. Archived elements are excluded.",
        "",
        "## Objective",
        "",
        first["objective"],
        "",
    ]
    if first.get("notes"):
        lines += ["## Notes", "", first["notes"], ""]

    counts = {}
    for etype, heading, lead in SECTIONS:
        section = [e for e in rows if e["element_type"] == etype]
        counts[etype] = len(section)
        lines += [f"## {heading}", "", lead, ""]
        if not section:
            lines += ["(None listed.)", ""]
            continue
        for e in section:
            indent = "  " if e["parent_code"] else ""
            lines.append(f"{indent}- **{e['code']}** {e['text']}")
        lines.append("")

    out = subject_path(subject_code, title, area)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{subject_code} {title}: K={counts['K']} R={counts['R']} S={counts['S']} "
          f"-> {out.relative_to(ROOT)}")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("subjects", nargs="*", help="subject codes, e.g. AM.II.E")
    ap.add_argument("--all-built", action="store_true",
                    help="regenerate every subject that already has an acs.md")
    args = ap.parse_args()

    elements = load_elements()
    codes = list(args.subjects)
    if args.all_built:
        for f in (ROOT / "subjects").glob("*/*/acs.md"):
            m = re.match(r"# (AM\.[IV]+\.[A-Z]+) ", f.read_text(encoding="utf-8"))
            if m:
                codes.append(m.group(1))
    if not codes:
        ap.error("give at least one subject code, or --all-built")

    commit = data_commit()
    for code in dict.fromkeys(codes):
        if not re.fullmatch(r"AM\.(I|II|III)\.[A-Z]+", code):
            sys.exit(f"Not a mechanic ACS subject code: {code}")
        build(code, elements, commit)


if __name__ == "__main__":
    main()
